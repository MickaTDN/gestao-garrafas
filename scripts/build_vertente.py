"""Deterministic offline shell version; no dependencies or private input."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "vertente"
PUBLIC = [
    "index.html",
    "manifest.webmanifest",
    "assets/app.css",
    "assets/app.js",
    "assets/domain.js",
    "assets/store.js",
    "assets/icon-192.png",
    "assets/icon-512.png",
]


def build():
    assets = sorted(ROOT / name for name in PUBLIC)
    digest = hashlib.sha256(
        b"".join(path.relative_to(ROOT).as_posix().encode() + path.read_bytes() for path in assets)
    ).hexdigest()[:20]
    urls = ["/", *("/" + path.relative_to(ROOT).as_posix() for path in assets)]
    return f"""// Generated by scripts/build_vertente.py; shell only, never stock or preferences.
const CACHE = 'vertente-shell-{digest}';
const ASSETS = new Set({json.dumps(urls)});
self.addEventListener('install', event => event.waitUntil(caches.open(CACHE).then(cache => cache.addAll([...ASSETS]))));
self.addEventListener('activate', event => event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('vertente-shell-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', event => {{
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {{
    // Consultation must open immediately even on mobile data while the office is unreachable.
    event.respondWith(caches.match('/index.html').then(shell => shell || fetch(request)));
  }} else if (!url.search && ASSETS.has(url.pathname)) {{
    event.respondWith(caches.open(CACHE).then(cache => cache.match(request).then(found => found || fetch(request))));
  }}
}});
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "service-worker.js"
    expected = build()
    if args.check:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit("Offline shell outdated: run python scripts/build_vertente.py")
    else:
        path.write_text(expected)
        for directory in (ROOT, ROOT / "assets"):
            directory.chmod(0o755)
        for asset in [path, *(ROOT / name for name in PUBLIC)]:
            asset.chmod(0o644)
